/** Real AtomicFile and Keystore, exclusively inside a debug emulator's dedicated fixture directory. */
class BillingCacheAndroidTest {
    private lateinit var base: Context
    private lateinit var context: Context
    private lateinit var directory: File
    private var accountHashBefore: ByteArray? = null
    private val fixtureKeys = mutableListOf<AndroidVaultKeySource>()

    @Before fun prepare() {
        base = InstrumentationRegistry.getInstrumentation().targetContext
        check(base.packageName.endsWith(".debug") && Build.HARDWARE in setOf("ranchu", "goldfish"))
        accountHashBefore = actualAccountHash()
        val root = File(base.noBackupFilesDir, "instrumentation-billingcache")
        check(root.mkdirs() || root.isDirectory)
        directory = File(root, UUID.randomUUID().toString())
        check(directory.mkdir())
        context = object : ContextWrapper(base) {
            override fun getNoBackupFilesDir(): File = directory
            override fun getApplicationContext(): Context = this
        }
    }

    @After fun cleanup() {
        if (::directory.isInitialized) {
            assertArrayEquals("Fixture cache operations may not touch the app's account file", accountHashBefore, actualAccountHash())
            val root = File(base.noBackupFilesDir, "instrumentation-billingcache").canonicalFile
            check(directory.canonicalFile.parentFile == root)
            check(directory.deleteRecursively())
        }
        // Only aliases generated by this test are retired, never the production cache/account alias.
        fixtureKeys.forEach { it.clear() }
    }

    private fun fixtureKey(label: String) = AndroidVaultKeySource("gongxiaozhu.instrumentation.billing.$label.${UUID.randomUUID()}")
        .also(fixtureKeys::add)
    private fun actualAccountHash(): ByteArray? = File(base.noBackupFilesDir, "accounts.vault").takeIf { it.isFile }
        ?.readBytes()?.let { MessageDigest.getInstance("SHA-256").digest(it) }
    private fun cacheFile() = File(directory, "billing-cache.vault")
    private fun sample(account: String = "fictional-cache-account-a", time: Long = 1000) = CachedBilling(account, BillingSnapshot(
        mapOf("已用流量" to BillingMetric("1.250", "MB"), "账户余额" to BillingMetric("15.123", "元")),
        listOf(OnlineDevice("fictional-live-session-do-not-cache", "192.0.2.17", "2001:db8::17",
            "00:00:5e:00:53:17", "2026-11-20 08:00", 15, BillingMetric("1.234", "MB")))), time)
    private fun CachedBilling.displayOnly() = copy(snapshot = snapshot.copy(devices = snapshot.devices.mapIndexed { index, device ->
        device.copy(sessionId = "cached-device-$index")
    }))

    @Test fun factoryKeepsOneLatestBoundedEncryptedFileAcrossRepositoryRecreation() {
        val first = sample(); val second = sample("fictional-cache-account-b", 2000)
        val repository = createBillingCacheRepository(context)
        assertTrue(repository.save(first))
        val original = cacheFile().readBytes()
        assertTrue(repository.save(second)); assertTrue(repository.save(second))
        val restored = createBillingCacheRepository(context)
        assertNull(restored.load(first.accountId))
        assertEquals(second.displayOnly(), restored.load(second.accountId))
        assertTrue(cacheFile().length() in 32..BILLING_CACHE_MAX_BYTES.toLong())
        assertEquals(setOf("billing-cache.vault"), directory.listFiles()!!.map { it.name }.toSet())
        assertTrue(cacheFile().canonicalPath.startsWith(base.noBackupFilesDir.canonicalPath + File.separator))
        assertFalse(original.contentEquals(cacheFile().readBytes()))
        val encrypted = cacheFile().readBytes().toString(Charsets.ISO_8859_1)
        for (text in listOf(second.accountId, "192.0.2.17", "fictional-live-session-do-not-cache")) assertFalse(encrypted.contains(text))
        val plaintext = AesGcmVaultCipher(AndroidVaultKeySource("gongxiaozhu.billing.cache.v1")).decrypt(cacheFile().readBytes())
        try {
            val json = plaintext.decodeToString()
            assertFalse(json.contains("sessionId")); assertFalse(json.contains("fictional-live-session-do-not-cache"))
        } finally { plaintext.fill(0) }
        assertTrue(restored.clear()); assertTrue(directory.listFiles()!!.isEmpty())
    }

    @Test fun corruptCacheAndMissingTestKeyDoNotBlockOrChangeAccountStorage() {
        val sentinel = File(directory, "unrelated-fixture.txt").apply { writeText("fictional unrelated data") }
        val accountKey = fixtureKey("accounts")
        val accounts = AccountRepository(AndroidVaultStore(context, "accounts-fixture.vault"), AesGcmVaultCipher(accountKey))
        accounts.load()
        val account = accounts.save(AccountDraft(label = "虚构账号", username = "fictional-cache-user",
            password = "fictional-cache-password")).defaultAccount!!
        val accountBytes = File(directory, "accounts-fixture.vault").readBytes()
        val cacheKey = fixtureKey("cache-loss")
        val repository = BillingCacheRepository(AndroidBillingCacheStore(context), AesGcmVaultCipher(cacheKey))
        assertTrue(repository.save(sample()))
        cacheFile().writeBytes(byteArrayOf(1, 2, 3))
        assertNull(repository.load(sample().accountId))
        cacheFile().writeBytes(ByteArray(BILLING_CACHE_MAX_BYTES + 1))
        assertNull(repository.load(sample().accountId))
        assertTrue(repository.save(sample()))
        cacheKey.clear() // A dedicated test alias models key loss; the factory alias is never deleted.
        assertNull(repository.load(sample().accountId))
        assertTrue(repository.clear())
        assertEquals("fictional-cache-password", accounts.edit(account.id).password)
        assertArrayEquals(accountBytes, File(directory, "accounts-fixture.vault").readBytes())
        assertEquals("fictional unrelated data", sentinel.readText())
        assertArrayEquals(accountHashBefore, actualAccountHash())
    }

    @Test fun oversizedAtomicWritesAndSnapshotsPreserveTheLastGoodCache() {
        val repository = createBillingCacheRepository(context); val good = sample()
        assertTrue(repository.save(good)); val before = cacheFile().readBytes()
        assertThrows(IllegalArgumentException::class.java) {
            AndroidBillingCacheStore(context).write(ByteArray(BILLING_CACHE_MAX_BYTES + 1))
        }
        assertArrayEquals(before, cacheFile().readBytes())
        val huge = good.copy(snapshot = good.snapshot.copy(devices = (1..64).map {
            OnlineDevice("discarded-session-$it", "地".repeat(128), "址".repeat(128), "网".repeat(64),
                "时".repeat(128), 1, BillingMetric("量".repeat(128), "单".repeat(32)))
        }))
        assertFalse(repository.save(huge))
        assertArrayEquals(before, cacheFile().readBytes())
        assertEquals(good.displayOnly(), createBillingCacheRepository(context).load(good.accountId))
        assertEquals(setOf("billing-cache.vault"), directory.listFiles()!!.map { it.name }.toSet())
        assertTrue(repository.clear())
    }

    @Test fun controllerPersistsThenColdRestoresEncryptedHistoryAndAutomaticallyRefreshesOnlyOnce() = runBlocking {
        val firstJob = SupervisorJob()
        val secondJob = SupervisorJob()
        val firstScope = CoroutineScope(firstJob + Dispatchers.Main.immediate)
        val secondScope = CoroutineScope(secondJob + Dispatchers.Main.immediate)
        val firstState = MutableStateFlow(BillingUiState())
        val secondState = MutableStateFlow(BillingUiState())
        val firstCalls = AtomicInteger()
        val secondCalls = AtomicInteger()
        val closed = AtomicInteger()
        val failure = CompletableDeferred<Unit>()
        val good = sample()
        fun session(action: suspend () -> BillingSnapshot) = object : BillingSession {
            override suspend fun refresh(credentials: AccountDraft, code: String?): BillingSnapshot {
                assertEquals(good.accountId, credentials.id)
                return action()
            }
            override suspend fun offlineTip(): String = error("Historical devices must not request logout")
            override suspend fun offline(device: OnlineDevice) { error("No device logout expected") }
            override fun close() { closed.incrementAndGet() }
        }
        val successful = session { firstCalls.incrementAndGet(); good.snapshot }
        val failing = session { secondCalls.incrementAndGet(); failure.await(); throw BillingException(BillingProblem.CONNECTION) }
        fun wifi(session: BillingSession) = WifiConnection("fictional-cache-integration-wifi",
            PortalTransport { error("No campus HTTP expected") }, billingSession = { session })
        fun credentials(id: String) = AccountDraft(id, "虚构缓存账号", "fictional-cache-user", "fictional-cache-password")
        val first = BillingController(firstScope, { credentials(it) }, { firstState.value = it },
            { error("Optional billing cache cannot block account storage") }, {}, cache = createBillingCacheRepository(context))
        try {
            withContext(Dispatchers.Main.immediate) {
                first.accountChanged(good.accountId); first.wifiChanged(wifi(successful)); first.enterForeground(); first.query()
            }
            val live = withTimeout(10_000) { firstState.first { it.snapshot == good.snapshot && !it.running } }
            val successTime = checkNotNull(live.loadedAt)
            assertEquals(1, firstCalls.get()); assertTrue(successTime > 0)
            // Wait for the real asynchronous AtomicFile save before any second reader opens it.
            withTimeout(10_000) {
                var pending = withContext(Dispatchers.Main.immediate) { firstJob.children.toList() }
                while (pending.isNotEmpty()) {
                    pending.joinAll()
                    pending = withContext(Dispatchers.Main.immediate) { firstJob.children.toList() }
                }
            }
            val expected = good.copy(loadedAt = successTime).displayOnly()
            assertEquals(expected, createBillingCacheRepository(context).load(good.accountId))
            val encrypted = cacheFile().readBytes()
            withContext(Dispatchers.Main.immediate) { first.leaveForeground() }
            firstJob.cancelAndJoin()
            val second = BillingController(secondScope, { credentials(it) }, { secondState.value = it },
                { error("Optional billing cache cannot block account storage") }, {}, cache = createBillingCacheRepository(context))
            withContext(Dispatchers.Main.immediate) { second.accountChanged(good.accountId) }
            val cold = withTimeout(10_000) { secondState.first { it.snapshotFromCache && it.snapshot != null } }
            assertEquals(expected.snapshot, cold.snapshot); assertEquals(live.loadedAt, cold.loadedAt)
            assertFalse(cold.devicesActionable); assertFalse(cold.queryFailed); assertEquals(0, secondCalls.get())
            val route = wifi(failing)
            withContext(Dispatchers.Main.immediate) { second.enterForeground(); second.setVisible(true); second.wifiChanged(route) }
            val refreshing = withTimeout(10_000) { secondState.first { it.running } }
            assertEquals(expected.snapshot, refreshing.snapshot); assertEquals(live.loadedAt, refreshing.loadedAt)
            failure.complete(Unit)
            val failed = withTimeout(10_000) { secondState.first { !it.running && it.queryFailed } }
            assertEquals(expected.snapshot, failed.snapshot); assertEquals(live.loadedAt, failed.loadedAt)
            assertTrue(failed.snapshotFromCache); assertFalse(failed.devicesActionable)
            withContext(Dispatchers.Main.immediate) {
                repeat(3) { second.setVisible(false); second.setVisible(true); second.enterForeground(); second.wifiChanged(route) }
            }
            InstrumentationRegistry.getInstrumentation().waitForIdleSync()
            assertEquals(1, secondCalls.get())
            assertTrue(closed.get() >= 1)
            assertArrayEquals(encrypted, cacheFile().readBytes())
            assertEquals(expected, createBillingCacheRepository(context).load(good.accountId))
        } finally {
            failure.complete(Unit)
            firstJob.cancelAndJoin(); secondJob.cancelAndJoin()
        }
    }
}
